// asset_report: reads every glTF/GLB under assets/ with cgltf and writes docs/asset_report.md.
// Usage: asset_report <assets_dir> <out.md>
#include <algorithm>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <map>
#include <sstream>

#include "engine/gltf_inspect.h"

namespace fs = std::filesystem;

static std::string Fmt(float v) {
    char b[32];
    std::snprintf(b, sizeof b, "%.3f", v);
    return b;
}

static std::string Aabb(const lk::GltfAabb& a) {
    if (!a.valid) return "-";
    std::ostringstream s;
    s << "min (" << Fmt(a.min[0]) << ", " << Fmt(a.min[1]) << ", " << Fmt(a.min[2]) << ") max (" << Fmt(a.max[0])
      << ", " << Fmt(a.max[1]) << ", " << Fmt(a.max[2]) << ") size (" << Fmt(a.max[0] - a.min[0]) << ", "
      << Fmt(a.max[1] - a.min[1]) << ", " << Fmt(a.max[2] - a.min[2]) << ")";
    return s.str();
}

int main(int argc, char** argv) {
    if (argc < 3) {
        std::fprintf(stderr, "usage: asset_report <assets_dir> <out.md>\n");
        return 2;
    }
    fs::path root = argv[1];
    std::vector<fs::path> files;
    for (auto& e : fs::recursive_directory_iterator(root)) {
        if (!e.is_regular_file()) continue;
        auto ext = e.path().extension().string();
        std::transform(ext.begin(), ext.end(), ext.begin(), ::tolower);
        if (ext == ".gltf" || ext == ".glb") files.push_back(e.path());
    }
    std::sort(files.begin(), files.end());

    std::map<std::string, std::vector<lk::GltfReport>> byPack;
    int failures = 0;
    for (auto& f : files) {
        auto rel = fs::relative(f, root).generic_string();
        auto pack = rel.substr(0, rel.find('/'));
        auto rep = lk::InspectGltf(f.string());
        rep.path = rel;
        if (!rep.ok) ++failures;
        byPack[pack].push_back(std::move(rep));
    }

    std::ostringstream md;
    md << "# Asset report\n\n";
    md << "Generated by `tools/asset_report` (cgltf). Do not edit by hand; rerun:\n\n";
    md << "```\nbuild/release/bin/asset_report assets docs/asset_report.md\n```\n\n";
    md << "Files: " << files.size() << ", parse failures: " << failures << "\n\n";

    md << "## Summary\n\n| Pack | File | Meshes | Bones | Clips | Scene AABB size (x, y, z) |\n|---|---|---|---|---|---|\n";
    for (auto& [pack, reps] : byPack)
        for (auto& r : reps) {
            std::string size = "-";
            if (r.sceneAabb.valid)
                size = Fmt(r.sceneAabb.max[0] - r.sceneAabb.min[0]) + ", " + Fmt(r.sceneAabb.max[1] - r.sceneAabb.min[1]) +
                       ", " + Fmt(r.sceneAabb.max[2] - r.sceneAabb.min[2]);
            md << "| " << pack << " | " << r.path << " | " << r.meshes.size() << " | " << r.bones.size() << " | "
               << r.clips.size() << " | " << (r.ok ? size : "PARSE ERROR: " + r.error) << " |\n";
        }

    md << "\n## Animation storage\n\n";
    md << "Animations live **inside the character files** (each KayKit character GLB carries its own clips; "
          "all characters in a pack share the same rig). No separate animation files exist in these packs.\n\n";

    for (auto& [pack, reps] : byPack) {
        md << "## Pack: " << pack << "\n\n";
        for (auto& r : reps) {
            md << "### " << r.path << "\n\n";
            if (!r.ok) {
                md << "**Parse error:** " << r.error << "\n\n";
                continue;
            }
            md << "- skins: " << r.skins << ", materials: " << r.materials << ", images: " << r.images << "\n";
            md << "- scene AABB: " << Aabb(r.sceneAabb) << "\n\n";
            // Detail only for rigged / animated files and small static files.
            md << "Node tree:\n\n```\n";
            int shown = 0;
            for (auto& n : r.nodes) {
                if (n.isJoint) continue;  // joints listed separately
                if (++shown > 60) {
                    md << "...\n";
                    break;
                }
                md << std::string(size_t(n.depth) * 2, ' ') << n.name;
                if (!n.mesh.empty()) md << "  [mesh: " << n.mesh << "]";
                md << "\n";
            }
            md << "```\n\n";
            md << "Meshes:\n\n";
            for (auto& m : r.meshes)
                md << "- `" << m.name << "` (" << m.primitives << " prim, " << m.vertices << " verts) AABB " << Aabb(m.aabb)
                   << "\n";
            md << "\n";
            if (!r.bones.empty()) {
                md << "Bones (" << r.bones.size() << ", skin 0 joint order):\n\n```\n";
                for (size_t i = 0; i < r.bones.size(); ++i) md << i << ": " << r.bones[i] << "\n";
                md << "```\n\n";
            }
            if (!r.clips.empty()) {
                md << "Animation clips (" << r.clips.size() << "):\n\n| # | Clip | Duration (s) |\n|---|---|---|\n";
                for (size_t i = 0; i < r.clips.size(); ++i)
                    md << "| " << i << " | `" << r.clips[i].name << "` | " << Fmt(r.clips[i].duration) << " |\n";
                md << "\n";
            }
        }
    }

    std::ofstream out(argv[2], std::ios::binary);
    out << md.str();
    std::printf("asset_report: %zu files, %d failures -> %s\n", files.size(), failures, argv[2]);
    return failures ? 1 : 0;
}
