#include "game/anim_report.h"

#include <cmath>
#include <fstream>
#include <sstream>

#include "engine/assets.h"
#include "engine/data_store.h"
#include "engine/log.h"
#include "game/character_visual.h"
#include "game/context.h"

namespace lk {

int WriteAnimReport(Ctx& ctx, const std::string& outPath) {
    std::ostringstream md;
    md << "# Attack timing report\n\n";
    md << "Generated by `LanternKnight --anim-report`. For each attack action the weapon tip (handslot.r, +Y 1.3 units)\n"
          "is sampled every 1/120 s of clip time. *Swing* is the span where tip speed stays above 45% of its peak.\n"
          "The anim maps in data/anims/ use these as `hit` / `hit_end` (clip seconds).\n\n";
    int problems = 0;
    for (const auto& file : ctx.data.Files()) {
        if (file.rfind("anims/", 0) != 0) continue;
        const json& map = ctx.data.Get(file);
        CharacterVisual vis;
        if (!vis.Init(ctx.assets, map)) {
            ++problems;
            continue;
        }
        int hand = vis.Bone("handslot.r");
        md << "## " << file << "\n\n| Action | Clip | Duration | Peak at | Swing start | Swing end | Data hit | Data hit_end |\n|---|---|---|---|---|---|---|---|\n";
        for (auto& [name, a] : map["actions"].items()) {
            bool attack = a.contains("hit") && name != "drink";
            if (!attack) continue;
            const ActionInfo* info = vis.Info(name);
            if (!info) continue;
            vis.Play(name, 0.0f, true);
            vis.Anim().SetSpeedScale(1.0f);
            const float dt = 1.0f / 120.0f;
            std::vector<float> speed;
            Vector3 prev{};
            bool have = false;
            // Animator speed applies per-clip speed; step in real time then convert back to clip time.
            float realDur = info->RealDuration();
            int steps = int(realDur / dt) + 1;
            for (int i = 0; i <= steps; ++i) {
                vis.Update(i == 0 ? 0.0f : dt);
                Matrix bm = vis.Anim().BoneModel(hand);
                Vector3 tip = Vector3Transform(Vector3{0, 1.3f, 0}, bm);
                speed.push_back(have ? Vector3Distance(tip, prev) / dt : 0.0f);
                prev = tip;
                have = true;
            }
            // Ignore the first 12% and last 10% (wind-up jerks and settling).
            size_t lo = size_t(float(speed.size()) * 0.12f), hi = size_t(float(speed.size()) * 0.9f);
            size_t peak = lo;
            for (size_t i = lo; i < hi; ++i)
                if (speed[i] > speed[peak]) peak = i;
            float thr = speed[peak] * 0.45f;
            size_t s = peak, e = peak;
            while (s > lo && speed[s - 1] >= thr) --s;
            while (e + 1 < speed.size() && speed[e + 1] >= thr) ++e;
            auto clipT = [&](size_t i) { return float(i) * dt * info->speed; };
            char buf[256];
            std::snprintf(buf, sizeof buf, "| %s | %s | %.3f | %.3f | %.3f | %.3f | %.3f | %.3f |\n", name.c_str(),
                          a.value("clip", "").c_str(), info->duration, clipT(peak), clipT(s > 0 ? s - 1 : 0), clipT(e), info->hit,
                          info->hitEnd);
            md << buf;
        }
        md << "\n";
    }
    std::ofstream out(outPath, std::ios::binary);
    out << md.str();
    LK_INFO("anim report -> %s", outPath.c_str());
    return problems;
}

}  // namespace lk
